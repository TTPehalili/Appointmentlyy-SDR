/**
 * Background generation of a Meeting Action Plan: research the prospect, then write the AE's plan and
 * the customer one-pager. Started with after() from POST /api/meeting-plans and /regenerate, so the
 * rep's request returns at once. Never throws; failures are saved on the plan as friendly text.
 */
import { getTenantStore } from '@/lib/server/tenantStore';
import { getCompanyProfileStore, getMeetingPlanStore } from '@/lib/server/meetingPlanStore';
import { researchCompany } from '@/lib/server/meetingPlan/research';
import { generateActionPlan } from '@/lib/server/meetingPlan/plan';
import type { ResearchSummary } from '@/lib/meetingPlan';

/** Plans being generated by this server instance (guards against a double run of the same id). */
const running = new Set<string>();
const key = (tenantCode: string, id: string) => `${tenantCode}:${id}`;

export const isMeetingPlanRunning = (tenantCode: string, id: string) => running.has(key(tenantCode, id));

const GENERIC_FAILURE = 'We could not prepare this plan right now. Please try again in a minute.';

/**
 * Text safe to show a person. AI modules throw friendly messages; anything that looks technical
 * (configuration, stack traces, provider payloads) becomes a plain retry message.
 */
export function friendlyError(err: unknown, fallback: string): string {
  const msg = err instanceof Error ? err.message : '';
  if (/GOOGLE_API_KEY|api[_ ]?key|not configured/i.test(msg)) {
    return 'AI writing is not available on this server right now, so this could not be prepared. Please try again later.';
  }
  if (!msg || msg.length > 200 || /[{}<>]|https?:\/\/|\n|\bat\s+\S+\s+\(/.test(msg)) return fallback;
  return msg;
}

export async function runMeetingPlanJob(tenantCode: string, id: string): Promise<void> {
  const k = key(tenantCode, id);
  if (running.has(k)) return;
  running.add(k);
  let research: ResearchSummary | null = null;
  try {
    const store = getMeetingPlanStore();
    const plan = await store.get(tenantCode, id);
    if (!plan || plan.status !== 'preparing') return;

    const [tenant, profile] = await Promise.all([
      getTenantStore().getTenant(tenantCode),
      getCompanyProfileStore()
        .get(tenantCode)
        .catch((err) => {
          console.error('[meeting-plan job] profile', err);
          return null;
        }),
    ]);
    const tenantName = (tenant?.branding?.displayName || '').trim() || tenant?.name || 'our team';

    research = await researchCompany({ lead: plan.lead, call: plan.call });
    const out = await generateActionPlan({
      lead: plan.lead,
      call: plan.call,
      research,
      profile,
      tenantName,
      aeName: plan.assignedAeName || plan.assignedAe,
    });
    await store.update(tenantCode, id, { research, plan: out.plan, onePager: out.onePager, status: 'ready', error: null });
  } catch (err) {
    console.error('[meeting-plan job]', tenantCode, id, err instanceof Error ? err.message : err);
    try {
      // Keep the research when only the writing step failed; keep any earlier plan on a failed regenerate.
      await getMeetingPlanStore().update(tenantCode, id, {
        status: 'failed',
        error: friendlyError(err, GENERIC_FAILURE),
        ...(research ? { research } : {}),
      });
    } catch (saveErr) {
      console.error('[meeting-plan job] could not save the failure', saveErr);
    }
  } finally {
    running.delete(k);
  }
}
