// Converts markdown text to clean HTML string for rich email pasting
export function generateEmailHtml(markdown: string): string {
  const lines = markdown.split('\n');
  let html = `<div style="font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif; color: #222021; line-height: 1.6; max-width: 680px; padding: 20px; border: 1px solid #e2e0df; border-radius: 8px; background-color: #ffffff;">`;

  let inTable = false;
  let tableRows: string[][] = [];

  for (let i = 0; i < lines.length; i++) {
    let line = lines[i].trim();

    // Table detection
    if (line.startsWith('|') && line.endsWith('|')) {
      if (!inTable) {
        inTable = true;
        tableRows = [];
      }
      // Check if separator line
      if (/^\|(\s*:?-+:?\s*\|)+$/.test(line)) {
        continue;
      }
      const cells = line.split('|').map(c => c.trim()).filter((_, idx, arr) => idx !== 0 && idx !== arr.length - 1);
      tableRows.push(cells);
      continue;
    } else if (inTable) {
      // Flush table
      html += renderHtmlTable(tableRows);
      inTable = false;
      tableRows = [];
    }

    if (!line) {
      html += `<div style="height: 12px;"></div>`;
      continue;
    }

    // Headings
    if (line.startsWith('### ')) {
      const heading = line.replace('### ', '');
      html += `<h3 style="font-size: 16px; font-weight: 800; color: #222021; margin: 18px 0 8px 0; border-bottom: 2px solid #ED1C24; padding-bottom: 4px;">${cleanFormatting(heading)}</h3>`;
      continue;
    }
    if (line.startsWith('#### ')) {
      const heading = line.replace('#### ', '');
      html += `<h4 style="font-size: 14px; font-weight: 700; color: #222021; margin: 14px 0 6px 0;">${cleanFormatting(heading)}</h4>`;
      continue;
    }

    // Blockquote
    if (line.startsWith('> ')) {
      const quote = line.replace('> ', '');
      html += `<div style="background-color: #F7F6F5; border-left: 4px solid #ED1C24; padding: 12px 16px; margin: 12px 0; font-size: 13px; color: #222021; border-radius: 4px;">${formatInline(quote)}</div>`;
      continue;
    }

    // List items
    if (/^(\*|-|\d+\.)\s/.test(line)) {
      const text = line.replace(/^(\*|-|\d+\.)\s/, '');
      if (text.includes('The Data:')) {
        html += `<div style="background-color: #f8fafc; border-left: 3px solid #222021; padding: 8px 12px; margin: 8px 0; border-radius: 4px; font-size: 13px;">${formatInline(text)}</div>`;
      } else if (text.includes("Why It's Impacting:")) {
        html += `<div style="background-color: #fafaf9; border-left: 3px solid #6b6968; padding: 8px 12px; margin: 8px 0; border-radius: 4px; font-size: 13px;">${formatInline(text)}</div>`;
      } else if (text.includes('Recommended Steps') || text.includes('Action Item') || text.includes('Action Plan')) {
        html += `<div style="background-color: #fff8f8; border-left: 3px solid #ED1C24; padding: 8px 12px; margin: 8px 0; border-radius: 4px; font-size: 13px;">${formatInline(text)}</div>`;
      } else {
        html += `<div style="padding-left: 16px; margin-bottom: 6px; font-size: 13px; color: #333130;"><span style="color: #ED1C24; font-weight: bold; margin-right: 8px;">•</span>${formatInline(text)}</div>`;
      }
      continue;
    }

    // Horizontal Rule
    if (line === '---') {
      html += `<hr style="border: none; border-top: 1px solid #e8e6e5; margin: 16px 0;" />`;
      continue;
    }

    // Regular paragraph
    html += `<p style="margin: 6px 0; font-size: 13px; color: #333130;">${formatInline(line)}</p>`;
  }

  if (inTable) {
    html += renderHtmlTable(tableRows);
  }

  html += `<div style="margin-top: 24px; padding-top: 12px; border-top: 1px solid #e8e6e5; font-size: 11px; color: #8c8987; font-family: monospace;">Generated by Appointmentlyy AI Boris Operations Intelligence • Confidential</div></div>`;
  return html;
}

function renderHtmlTable(rows: string[][]): string {
  if (rows.length === 0) return '';
  const [header, ...body] = rows;

  let out = `<table style="width: 100%; border-collapse: collapse; margin: 14px 0; font-size: 12px; border: 1px solid #e2e0df;"><thead><tr style="background-color: #222021; color: #ffffff;">`;
  for (const h of header) {
    out += `<th style="padding: 10px 12px; text-align: left; font-weight: 700; border-bottom: 1px solid #e2e0df;">${cleanFormatting(h)}</th>`;
  }
  out += `</tr></thead><tbody>`;

  body.forEach((row, idx) => {
    const bg = idx % 2 === 0 ? '#ffffff' : '#f9f9f8';
    out += `<tr style="background-color: ${bg}; border-bottom: 1px solid #e8e6e5;">`;
    row.forEach((cell) => {
      out += `<td style="padding: 9px 12px; color: #222021;">${formatInline(cell)}</td>`;
    });
    out += `</tr>`;
  });

  out += `</tbody></table>`;
  return out;
}

function cleanFormatting(str: string): string {
  return str.replace(/\*\*/g, '').replace(/\*/g, '').replace(/`/g, '');
}

function formatInline(str: string): string {
  return str
    .replace(/\*\*(.*?)\*\*/g, '<strong style="color: #222021; font-weight: 700;">$1</strong>')
    .replace(/\*(.*?)\*/g, '<em style="color: #555352;">$1</em>')
    .replace(/`(.*?)`/g, '<code style="background-color: #e8e6e5; padding: 2px 4px; border-radius: 3px; font-size: 11px;">$1</code>');
}

// Converts markdown to clean plain text for email/Slack
export function generateCleanPlainText(markdown: string): string {
  return markdown
    .replace(/^###\s+/gm, '■ ')
    .replace(/^####\s+/gm, '▶ ')
    .replace(/\*\*(.*?)\*\*/g, '$1')
    .replace(/\*(.*?)\*/g, '$1')
    .replace(/`(.*?)`/g, '$1')
    .replace(/^>\s+/gm, 'NOTE: ');
}

export default function ExecutiveReportRenderer({ content, timestamp, queryTitle }: ExecutiveReportRendererProps) {
  const [copiedType, setCopiedType] = useState<'html' | 'text' | null>(null);

  // Copy rich HTML for pasting into Outlook / Gmail
  const handleCopyRichEmail = async () => {
    try {
      const html = generateEmailHtml(content);
      const text = generateCleanPlainText(content);

      if (typeof ClipboardItem !== 'undefined' && navigator.clipboard.write) {
        const item = new ClipboardItem({
          'text/html': new Blob([html], { type: 'text/html' }),
          'text/plain': new Blob([text], { type: 'text/plain' })
        });
        await navigator.clipboard.write([item]);
      } else {
        await navigator.clipboard.writeText(text);
      }
      setCopiedType('html');
      setTimeout(() => setCopiedType(null), 2500);
    } catch (err) {
      console.warn('Clipboard write failed, fallback to plain text', err);
      navigator.clipboard.writeText(generateCleanPlainText(content));
      setCopiedType('html');
      setTimeout(() => setCopiedType(null), 2500);
    }
  };

  const handleCopyPlainText = async () => {
    const text = generateCleanPlainText(content);
    await navigator.clipboard.writeText(text);
    setCopiedType('text');
    setTimeout(() => setCopiedType(null), 2500);
  };

  // Parse lines for UI rendering
  const lines = content.split('\n');
  const renderedElements: React.ReactNode[] = [];

  let tableBuffer: string[][] = [];
  let inTable = false;

  const flushTable = (key: string) => {
    if (tableBuffer.length === 0) return null;
    const [header, ...rows] = tableBuffer;
    tableBuffer = [];
    return (
      <div key={key} className="my-4 overflow-x-auto rounded-lg border border-line bg-surface">
        <table className="w-full text-left text-small border-collapse">
          <thead>
            <tr className="bg-subtle">
              {header.map((h, idx) => (
                <th key={idx} className="h-9 px-3.5 text-caption text-fg-tertiary border-b border-line">
                  {cleanFormatting(h)}
                </th>
              ))}
            </tr>
          </thead>
          <tbody>
            {rows.map((row, rIdx) => (
              <tr
                key={rIdx}
                className="border-t border-line first:border-t-0 transition-colors hover:bg-subtle"
              >
                {row.map((cell, cIdx) => {
                  const isFirstCol = cIdx === 0;
                  const hasIcon = cell.includes('🎯') || cell.includes('🚫') || cell.includes('🔄');
                  return (
                    <td key={cIdx} className={`py-2 px-3.5 tabular-nums ${isFirstCol ? 'font-medium text-fg' : 'text-fg-secondary'}`}>
                      {hasIcon ? (
                        <span className="inline-flex items-center gap-1.5 font-medium">
                          {cleanFormatting(cell)}
                        </span>
                      ) : (
                        <span>{cleanFormatting(cell)}</span>
                      )}
                    </td>
                  );
                })}
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    );
  };

  lines.forEach((rawLine, idx) => {
    const line = rawLine.trim();

    // Table parsing
    if (line.startsWith('|') && line.endsWith('|')) {
      if (!inTable) inTable = true;
      if (/^\|(\s*:?-+:?\s*\|)+$/.test(line)) return; // separator
      const cells = line.split('|').map(c => c.trim()).filter((_, i, arr) => i !== 0 && i !== arr.length - 1);
      tableBuffer.push(cells);
      return;
    } else if (inTable) {
      renderedElements.push(flushTable(`table-${idx}`));
      inTable = false;
    }

    if (!line) {
      renderedElements.push(<div key={`spacer-${idx}`} className="h-2" />);
      return;
    }

    // Section 1 Header (###)
    if (line.startsWith('### ')) {
      const heading = line.replace('### ', '');
      renderedElements.push(
        <div key={`h3-${idx}`} className="mt-5 mb-2 pb-1.5 border-b border-line">
          <h3 className="text-h3 text-fg">
            {cleanFormatting(heading)}
          </h3>
        </div>
      );
      return;
    }

    // Section 2 Header (####)
    if (line.startsWith('#### ')) {
      const heading = line.replace('#### ', '');
      const isPositive = heading.toLowerCase().includes('positive') || heading.toLowerCase().includes('boosting');
      const isNegative = heading.toLowerCase().includes('leak') || heading.toLowerCase().includes('negatively') || heading.toLowerCase().includes('bottleneck');

      renderedElements.push(
        <div key={`h4-${idx}`} className="mt-4 mb-2 flex flex-wrap items-center gap-2">
          <Badge tone={isPositive ? 'success' : isNegative ? 'danger' : 'neutral'}>
            {isPositive ? 'Positive drivers' : isNegative ? 'Conversion leaks' : 'Insight'}
          </Badge>
          <h4 className="text-body-strong text-fg">
            {cleanFormatting(heading)}
          </h4>
        </div>
      );
      return;
    }

    // Blockquote / Executive Takeaway
    if (line.startsWith('> ')) {
      const quote = line.replace('> ', '');
      renderedElements.push(
        <div key={`quote-${idx}`} className="my-3 rounded-lg border border-line bg-subtle p-3 text-body text-fg">
          <div className="flex items-center gap-1.5 text-caption text-fg-secondary mb-1">
            <Sparkles className="h-3.5 w-3.5" aria-hidden />
            <span>Executive takeaway</span>
          </div>
          <p>{cleanFormatting(quote).replace('Executive Takeaway:', '')}</p>
        </div>
      );
      return;
    }

    // List items
    if (/^(\*|-|\d+\.)\s/.test(line)) {
      const rawText = line.replace(/^(\*|-|\d+\.)\s/, '');
      const isTopLevel = line.startsWith('1.') || line.startsWith('2.') || line.startsWith('3.');
      const isData = rawText.includes('The Data:');
      const isWhy = rawText.includes("Why It's Impacting:");
      const isAction = rawText.includes('Recommended Steps') || rawText.includes('Action Item') || rawText.includes('Action Plan');

      if (isData) {
        renderedElements.push(
          <div key={`list-${idx}`} className="my-2 p-3 rounded-lg bg-surface border border-line text-body">
            <div className="flex items-center gap-1.5 mb-1 text-caption text-fg-secondary">
              <BarChart3 className="h-3.5 w-3.5" aria-hidden />
              <span>Verified call data</span>
            </div>
            <div className="text-body text-fg">
              {formatInlineText(rawText.replace(/\*\*📊 The Data:\*\*/, '').trim())}
            </div>
          </div>
        );
        return;
      }

      if (isWhy) {
        renderedElements.push(
          <div key={`list-${idx}`} className="my-2 p-3 rounded-lg bg-subtle border border-line text-body">
            <div className="flex items-center gap-1.5 mb-1 text-caption text-fg-secondary">
              <Lightbulb className="h-3.5 w-3.5" aria-hidden />
              <span>Root cause</span>
            </div>
            <div className="text-body text-fg">
              {formatInlineText(rawText.replace(/\*\*🧠 Why It's Impacting:\*\*/, '').trim())}
            </div>
          </div>
        );
        return;
      }

      if (isAction) {
        renderedElements.push(
          <div key={`list-${idx}`} className="my-2 p-3 rounded-lg bg-surface border border-line border-l-2 border-l-brand-600 text-body">
            <div className="flex items-center gap-1.5 mb-1 text-caption text-brand-text">
              <Target className="h-3.5 w-3.5" aria-hidden />
              <span>Recommended next steps</span>
            </div>
            <div className="text-body text-fg">
              {formatInlineText(rawText.replace(/\*\*🎯 Recommended Steps to Increase Performance:\*\*/, '').trim())}
            </div>
          </div>
        );
        return;
      }

      renderedElements.push(
        <div key={`list-${idx}`} className={`flex items-start gap-2.5 my-1.5 ${isTopLevel ? 'p-2.5 rounded-md border border-line' : 'pl-3'}`}>
          <span className={`shrink-0 rounded-full ${isTopLevel ? 'size-5 flex items-center justify-center bg-subtle text-fg-secondary text-caption tabular-nums' : 'size-1.5 mt-2 bg-fg-tertiary'}`}>
            {isTopLevel ? line.match(/^\d+/)?.[0] : ''}
          </span>
          <div className="text-body text-fg flex-1">
            {formatInlineText(rawText)}
          </div>
        </div>
      );
      return;
    }

    // Divider
    if (line === '---') {
      renderedElements.push(<hr key={`hr-${idx}`} className="my-3 border-line" />);
      return;
    }

    // Regular text
    renderedElements.push(
      <p key={`p-${idx}`} className="my-1 text-body text-fg">
        {formatInlineText(line)}
      </p>
    );
  });

  if (inTable) {
    renderedElements.push(flushTable('final-table'));
  }

  return (
    <div className="space-y-3">
      {/* EXECUTIVE COPY TOOLBAR FOR MANAGERS */}
      <div className="flex flex-wrap items-center justify-between gap-2 pb-2 mb-2 border-b border-line">
        <div className="flex items-center gap-2">
          <span className="text-h3 text-fg">
            Report
          </span>
          {timestamp && (
            <span className="text-caption text-fg-tertiary tabular-nums">
              {timestamp}
            </span>
          )}
        </div>

        <div className="flex items-center gap-1.5">
          <Button
            size="sm"
            variant="secondary"
            onClick={handleCopyRichEmail}
            title="Copies formatted table & styled HTML ready to paste directly into Gmail or Outlook"
            icon={copiedType === 'html' ? <Check className="text-success-fg" /> : <Mail className="text-fg-secondary" />}
          >
            {copiedType === 'html' ? 'Copied for email' : 'Copy for email'}
          </Button>

          <Button
            size="sm"
            variant="ghost"
            onClick={handleCopyPlainText}
            title="Copy clean plain text without markdown asterisks"
            icon={copiedType === 'text' ? <Check className="text-success-fg" /> : <FileText />}
          >
            {copiedType === 'text' ? 'Copied' : 'Copy text'}
          </Button>
        </div>
      </div>

      {/* RENDERED EXECUTIVE CONTENT */}
      <div className="text-body select-text">
        {renderedElements}
      </div>
    </div>
  );
}

// React helper for bold/italics in UI
function formatInlineText(text: string): React.ReactNode {
  const parts = text.split(/(\*\*.*?\*\*|\*.*?\*|`.*?`)/g);
  return parts.map((part, idx) => {
    if (part.startsWith('**') && part.endsWith('**')) {
      return (
        <strong key={idx} className="font-semibold text-fg">
          {part.slice(2, -2)}
        </strong>
      );
    }
    if (part.startsWith('*') && part.endsWith('*')) {
      return (
        <em key={idx} className="italic text-fg-secondary">
          {part.slice(1, -1)}
        </em>
      );
    }
    if (part.startsWith('`') && part.endsWith('`')) {
      return (
        <code key={idx} className="bg-subtle border border-line px-1 py-0.5 rounded-sm text-caption font-mono text-fg">
          {part.slice(1, -1)}
        </code>
      );
    }
    return part;
  });
}
